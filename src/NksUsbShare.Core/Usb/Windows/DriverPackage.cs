using System.Runtime.InteropServices;
using System.Runtime.Versioning;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using System.Text;

namespace NksUsbShare.Core.Usb.Windows;

/// <summary>
/// Builds the small driver package that points a device at the in-box winusb.sys: an INF, a
/// catalog covering it, and a signature the machine trusts.
///
/// Windows will not install a third-party INF without a signed catalog, so all three are needed.
/// None of it requires the WDK or any signing toolkit: the certificate comes from .NET, the
/// catalog from wintrust, and the signature from mssign32 — the call signtool itself makes.
///
/// NOT FINISHED, and not yet used by anything that ships. The INF, the certificate and the
/// signing work; <see cref="Catalog.Build"/> gets as far as adding the member and its attributes
/// and then CryptCATPersistStore writes a zero-length file without setting an error. Until that
/// is understood, <see cref="WinUsbBinder"/> still drives tools/bind-winusb.ps1, which is
/// verified against real hardware. The rest of the native path — the device tree, the forced
/// install, the port cycle — is proven and in use.
/// </summary>
[SupportedOSPlatform("windows")]
internal sealed class DriverPackage : IDisposable
{
    private const string CertificateSubject = "CN=NKS UsbShare Driver Signing";

    private DriverPackage(string directory, string infPath, string interfaceGuid)
    {
        Directory = directory;
        InfPath = infPath;
        InterfaceGuid = interfaceGuid;
    }

    public string Directory { get; }
    public string InfPath { get; }
    public string InterfaceGuid { get; }

    public void Dispose()
    {
        try { System.IO.Directory.Delete(Directory, recursive: true); }
        catch (IOException) { /* a temporary directory left behind is not worth failing over */ }
        catch (UnauthorizedAccessException) { }
    }

    /// <summary>Writes, catalogues and signs a package for one hardware id.</summary>
    public static DriverPackage Create(string hardwareId, string description, Action<string> report)
    {
        var directory = Path.Combine(Path.GetTempPath(), "nksusb-inf-" + Guid.NewGuid().ToString("N")[..8]);
        System.IO.Directory.CreateDirectory(directory);

        var interfaceGuid = "{" + Guid.NewGuid().ToString().ToUpperInvariant() + "}";
        var infPath = Path.Combine(directory, "nksusb.inf");

        // An INF is written UTF-16 with a byte order mark; Windows rejects it otherwise.
        File.WriteAllText(infPath, BuildInf(hardwareId, description, interfaceGuid), Encoding.Unicode);

        report("Building the driver catalog...");
        var catalogPath = Path.Combine(directory, "nksusb.cat");
        Catalog.Build(directory, catalogPath, hardwareId);

        report("Signing the catalog...");
        using var certificate = EnsureSigningCertificate(report);
        Catalog.Sign(catalogPath, certificate);

        return new DriverPackage(directory, infPath, interfaceGuid);
    }

    private static string BuildInf(string hardwareId, string description, string interfaceGuid)
    {
        var date = DateTime.Now.ToString("MM/dd/yyyy");

        // Class USBDevice with Include/Needs pointing at the in-box winusb.inf: the package
        // carries no binary of its own, it only says "use the WinUSB that is already here".
        // Two dollars, so the braces of a GUID stay literal and interpolation takes {{ }}.
        return $$"""
            ; Generated by NKS UsbShare. Binds one device to the in-box WinUSB driver so its
            ; transfers can be forwarded over the network. Remove this package to give it back.
            [Version]
            Signature   = "$Windows NT$"
            Class       = USBDevice
            ClassGuid   = {88BAE032-5A81-49f0-BC3D-A4FF138216D6}
            Provider    = %ProviderName%
            CatalogFile = nksusb.cat
            DriverVer   = {{date}},1.0.0.0
            PnpLockdown = 1

            [Manufacturer]
            %ProviderName% = Devices, NTamd64, NTarm64

            [Devices.NTamd64]
            %DeviceName% = USB_Install, {{hardwareId}}

            [Devices.NTarm64]
            %DeviceName% = USB_Install, {{hardwareId}}

            [USB_Install]
            Include = winusb.inf
            Needs   = WINUSB.NT

            [USB_Install.Services]
            Include = winusb.inf
            Needs   = WINUSB.NT.Services

            [USB_Install.HW]
            AddReg = AddDeviceInterfaceGuid

            [AddDeviceInterfaceGuid]
            HKR,,DeviceInterfaceGUIDs,0x10000,"{{interfaceGuid}}"

            [Strings]
            ProviderName = "NKS UsbShare"
            DeviceName   = "{{description}}"

            """;
    }

    /// <summary>
    /// Returns the machine's signing certificate, creating and trusting it on first use. Windows
    /// only installs a package whose catalog chains to a trusted root and whose signer is a
    /// trusted publisher, so the certificate goes into both machine stores — which is the reason
    /// this work needs administrator rights.
    /// </summary>
    private static X509Certificate2 EnsureSigningCertificate(Action<string> report)
    {
        using (var store = new X509Store(StoreName.My, StoreLocation.LocalMachine))
        {
            store.Open(OpenFlags.ReadOnly);
            foreach (var candidate in store.Certificates)
            {
                if (candidate.Subject == CertificateSubject &&
                    candidate.NotAfter > DateTime.Now.AddDays(30) &&
                    candidate.HasPrivateKey)
                {
                    return candidate;
                }
            }
        }

        report("Creating a driver signing certificate for this machine...");

        using var key = RSA.Create(3072);
        var request = new CertificateRequest(CertificateSubject, key, HashAlgorithmName.SHA256,
            RSASignaturePadding.Pkcs1);

        request.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.DigitalSignature, true));
        request.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(
            new OidCollection { new("1.3.6.1.5.5.7.3.3") }, true));   // code signing

        using var generated = request.CreateSelfSigned(DateTimeOffset.Now.AddDays(-1),
            DateTimeOffset.Now.AddYears(10));

        // The key has to be persisted for the machine, and an ephemeral key cannot be. Exporting
        // and re-importing is how a usable machine-store certificate is made.
        var password = Guid.NewGuid().ToString("N");
        var pfx = generated.Export(X509ContentType.Pfx, password);
        var certificate = X509CertificateLoader.LoadPkcs12(pfx, password,
            X509KeyStorageFlags.MachineKeySet | X509KeyStorageFlags.PersistKeySet | X509KeyStorageFlags.Exportable);

        AddTo(StoreName.My, certificate);
        AddTo(StoreName.Root, certificate);
        AddTo(StoreName.TrustedPublisher, certificate);

        return certificate;
    }

    private static void AddTo(StoreName name, X509Certificate2 certificate)
    {
        using var store = new X509Store(name, StoreLocation.LocalMachine);
        store.Open(OpenFlags.ReadWrite);
        store.Add(certificate);
    }

    /// <summary>Removes the signing certificate from every machine store it was put in.</summary>
    public static void RemoveSigningCertificate()
    {
        foreach (var name in (StoreName[])[StoreName.My, StoreName.Root, StoreName.TrustedPublisher])
        {
            using var store = new X509Store(name, StoreLocation.LocalMachine);
            store.Open(OpenFlags.ReadWrite);

            foreach (var certificate in store.Certificates)
                if (certificate.Subject == CertificateSubject)
                    store.Remove(certificate);
        }
    }

    /// <summary>The catalog: a list of the files in the package and their hashes, then signed.</summary>
    private static class Catalog
    {
        public static void Build(string directory, string catalogPath, string hardwareId)
        {
            var handle = DriverNative.CryptCATOpen(catalogPath, DriverNative.CryptcatOpenCreatenew,
                IntPtr.Zero, DriverNative.CryptcatVersion2,
                DriverNative.X509AsnEncoding | DriverNative.Pkcs7AsnEncoding);

            if (handle == IntPtr.Zero || handle == new IntPtr(-1))
                throw new UsbBackendException($"The catalog could not be created (Win32 {Marshal.GetLastWin32Error()}).");

            try
            {
                foreach (var file in System.IO.Directory.GetFiles(directory, "*.inf"))
                    AddMember(handle, file);

                // Windows matches a catalog to a device by this attribute when the package is
                // installed, so the hardware id has to be recorded in it.
                PutCatalogAttribute(handle, "HWID1", hardwareId);

                if (!DriverNative.CryptCATPersistStore(handle))
                    throw new UsbBackendException($"The catalog could not be written (Win32 {Marshal.GetLastWin32Error()}).");
            }
            finally
            {
                DriverNative.CryptCATClose(handle);
            }
        }

        /// <summary>
        /// The subject type Windows uses for a file that is not a signed binary. An INF is such a
        /// file: nothing claims it, so the lookup below fails and this is what a catalog records.
        /// </summary>
        private static readonly Guid FlatFileSubject = new("de351a42-8e59-11d0-8c47-00c04fc295ee");

        private static void AddMember(IntPtr catalog, string filePath)
        {
            if (!DriverNative.CryptSIPRetrieveSubjectGuid(filePath, IntPtr.Zero, out var subject))
                subject = FlatFileSubject;

            var indirect = CreateIndirectData(filePath, subject, out var indirectSize);

            try
            {
                var name = Path.GetFileName(filePath);
                var member = DriverNative.CryptCATPutMemberInfo(catalog, filePath, name, ref subject,
                    0x200, indirectSize, indirect);

                if (member == IntPtr.Zero)
                    throw new UsbBackendException($"'{name}' could not be added to the catalog (Win32 {Marshal.GetLastWin32Error()}).");

                PutMemberAttribute(catalog, member, "File", name);
                PutMemberAttribute(catalog, member, "OSAttr", "2:6.0,2:6.1,2:6.2,2:6.3,2:10.0");
            }
            finally
            {
                Marshal.FreeHGlobal(indirect);
            }
        }

        /// <summary>
        /// Asks the subject interface package for the file's hash in the shape a catalog stores.
        /// A flat file such as an INF is hashed whole; the SIP knows how, so this does not have to.
        /// </summary>
        private static IntPtr CreateIndirectData(string filePath, Guid subject, out uint size)
        {
            var dispatch = new DriverNative.SipDispatchInfo { Size = (uint)Marshal.SizeOf<DriverNative.SipDispatchInfo>() };
            if (!DriverNative.CryptSIPLoad(ref subject, 0, ref dispatch))
                throw new UsbBackendException($"The subject interface package could not be loaded (Win32 {Marshal.GetLastWin32Error()}).");

            var create = Marshal.GetDelegateForFunctionPointer<DriverNative.CryptSipCreateIndirectData>(dispatch.CreateIndirectData);

            using var file = File.OpenRead(filePath);
            var fileHandle = file.SafeFileHandle.DangerousGetHandle();

            var algorithm = Marshal.StringToHGlobalAnsi("2.16.840.1.101.3.4.2.1");   // SHA-256
            var name = Marshal.StringToHGlobalUni(filePath);
            var subjectGuid = Marshal.AllocHGlobal(Marshal.SizeOf<Guid>());
            Marshal.StructureToPtr(subject, subjectGuid, false);

            try
            {
                var info = new DriverNative.SipSubjectInfo
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SipSubjectInfo>(),
                    SubjectType = subjectGuid,
                    File = fileHandle,
                    FileName = name,
                    EncodingType = DriverNative.X509AsnEncoding | DriverNative.Pkcs7AsnEncoding,
                    DigestAlgorithm = new DriverNative.CryptAlgorithmIdentifier { ObjectId = algorithm },
                };

                uint needed = 0;
                if (!create(ref info, ref needed, IntPtr.Zero) || needed == 0)
                    throw new UsbBackendException($"The file hash could not be sized (Win32 {Marshal.GetLastWin32Error()}).");

                // The sizing call reads the file to the end. The real call has to start from the
                // beginning again or it hashes nothing and the catalog is quietly wrong.
                file.Position = 0;

                var buffer = Marshal.AllocHGlobal((int)needed);
                if (!create(ref info, ref needed, buffer))
                {
                    Marshal.FreeHGlobal(buffer);
                    throw new UsbBackendException($"The file hash could not be produced (Win32 {Marshal.GetLastWin32Error()}).");
                }

                size = needed;
                return buffer;
            }
            finally
            {
                Marshal.FreeHGlobal(algorithm);
                Marshal.FreeHGlobal(name);
                Marshal.FreeHGlobal(subjectGuid);
            }
        }

        private static void PutMemberAttribute(IntPtr catalog, IntPtr member, string tag, string value)
        {
            var buffer = Marshal.StringToHGlobalUni(value);
            try
            {
                var size = (uint)((value.Length + 1) * 2);
                var flags = DriverNative.CryptcatAttrNameascii | DriverNative.CryptcatAttrDataascii
                            | DriverNative.CryptcatAttrAuthenticated;

                if (DriverNative.CryptCATPutAttrInfo(catalog, member, tag, flags, size, buffer) == IntPtr.Zero)
                    throw new UsbBackendException($"The catalog attribute '{tag}' was refused (Win32 {Marshal.GetLastWin32Error()}).");
            }
            finally
            {
                Marshal.FreeHGlobal(buffer);
            }
        }

        private static void PutCatalogAttribute(IntPtr catalog, string tag, string value)
        {
            var buffer = Marshal.StringToHGlobalUni(value);
            try
            {
                var size = (uint)((value.Length + 1) * 2);
                var flags = DriverNative.CryptcatAttrNameascii | DriverNative.CryptcatAttrDataascii
                            | DriverNative.CryptcatAttrAuthenticated;

                if (DriverNative.CryptCATPutCatAttrInfo(catalog, tag, flags, size, buffer) == IntPtr.Zero)
                    throw new UsbBackendException($"The catalog attribute '{tag}' was refused (Win32 {Marshal.GetLastWin32Error()}).");
            }
            finally
            {
                Marshal.FreeHGlobal(buffer);
            }
        }

        /// <summary>
        /// Signs the catalog in place with SignerSignEx, the call signtool makes. The signature is
        /// produced by Windows itself, so nothing has to be added to the build to get one.
        /// </summary>
        public static void Sign(string catalogPath, X509Certificate2 certificate)
        {
            var fileName = Marshal.StringToHGlobalUni(catalogPath);
            var fileInfo = Marshal.AllocHGlobal(Marshal.SizeOf<DriverNative.SignerFileInfo>());
            var index = Marshal.AllocHGlobal(sizeof(uint));
            var storeInfo = Marshal.AllocHGlobal(Marshal.SizeOf<DriverNative.SignerCertStoreInfo>());

            try
            {
                Marshal.WriteInt32(index, 0);

                Marshal.StructureToPtr(new DriverNative.SignerFileInfo
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SignerFileInfo>(),
                    FileName = fileName,
                    File = IntPtr.Zero,
                }, fileInfo, false);

                Marshal.StructureToPtr(new DriverNative.SignerCertStoreInfo
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SignerCertStoreInfo>(),
                    SigningCert = certificate.Handle,
                    CertPolicy = DriverNative.CertPolicyStore,
                    CertStore = IntPtr.Zero,
                }, storeInfo, false);

                var subject = new DriverNative.SignerSubjectInfo
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SignerSubjectInfo>(),
                    Index = index,
                    SubjectChoice = DriverNative.SignerSubjectFile,
                    SubjectInfo = fileInfo,
                };

                var signer = new DriverNative.SignerCert
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SignerCert>(),
                    CertChoice = DriverNative.SignerCertStore,
                    CertInfo = storeInfo,
                    Window = IntPtr.Zero,
                };

                var signature = new DriverNative.SignerSignatureInfo
                {
                    Size = (uint)Marshal.SizeOf<DriverNative.SignerSignatureInfo>(),
                    AlgidHash = DriverNative.CalgSha256,
                    AttrChoice = DriverNative.SignerNoAttr,
                    AttrAuthcode = IntPtr.Zero,
                    AuthenticatedAttributes = IntPtr.Zero,
                    UnauthenticatedAttributes = IntPtr.Zero,
                };

                var result = DriverNative.SignerSignEx(0, ref subject, ref signer, ref signature,
                    IntPtr.Zero, null, IntPtr.Zero, IntPtr.Zero, out var context);

                if (context != IntPtr.Zero) DriverNative.SignerFreeSignerContext(context);

                if (result != 0)
                    throw new UsbBackendException($"The catalog could not be signed (HRESULT 0x{result:X8}).");
            }
            finally
            {
                Marshal.FreeHGlobal(fileName);
                Marshal.FreeHGlobal(fileInfo);
                Marshal.FreeHGlobal(index);
                Marshal.FreeHGlobal(storeInfo);
            }
        }
    }
}
